def normalize_language(value: str | None) -> str:
    code = (value or "en").lower()
    return code if code in SUPPORTED_LANGUAGES else "en"


def tr(language: str, key: str, **kwargs: Any) -> str:
    language = normalize_language(language)
    template = TRANSLATIONS.get(language, {}).get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, ValueError):
            return template
    return template


def month_abbr(language: str, month: int) -> str:
    language = normalize_language(language)
    values = MONTHS.get(language, MONTHS["en"])
    if 1 <= month <= 12:
        return values[month - 1]
    return ""

